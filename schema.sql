CREATE TABLE IF NOT EXISTS users(id TEXT PRIMARY KEY, name TEXT NOT NULL, role TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1, h TEXT NOT NULL, updated INTEGER);
CREATE TABLE IF NOT EXISTS recs(kind TEXT NOT NULL, id TEXT NOT NULL, data TEXT NOT NULL, owner TEXT, seq INTEGER NOT NULL, PRIMARY KEY(kind,id));
CREATE INDEX IF NOT EXISTS recs_seq ON recs(seq);
CREATE TABLE IF NOT EXISTS lock(k TEXT PRIMARY KEY, n INTEGER NOT NULL, t INTEGER NOT NULL);
